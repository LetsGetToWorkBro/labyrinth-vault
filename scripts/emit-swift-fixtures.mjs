/* ## The read-only Monero screen's fixture
 *
 * Different in kind from the two above, and the difference is the point of
 * emitting it. `summary.json` and `monero-summary.json` are built from inputs
 * written here. This one is built from `test/fixtures/monero-unsigned-tx-set.json`,
 * whose bytes came out of Monero's own `binary_archive` by way of the harness
 * in `oracle/` — so what Swift decodes here has been through the real
 * envelope, the real archive reader and the real converter, starting from
 * bytes this project did not write.
 *
 * The CryptoNight seam is the one substitution. The file was encrypted under
 * a view secret the oracle chose, and the only thing that secret does when
 * opening one of these is derive the ChaCha20 key; the fixture records that
 * key, so answering with it is the same code path with the vendored C stood
 * in for. `test/host-monerofile.test.ts` says the same thing at more length.
 */
const xmr = await loadSource(`
  export { setNativeCnSlowHash } from './src/keys/moneroexport';
  export { readUnsignedTxSetFile } from './src/keys/monerounsigned';
  export { readContainer } from './src/keys/monerotx';
  export { moneroFileToWire } from './src/bridge/summary';
`);

const hexBytes = (hex) => new Uint8Array(hex.match(/../g).map((pair) => parseInt(pair, 16)));

const oracle = JSON.parse(readFileSync('test/fixtures/monero-unsigned-tx-set.json', 'utf8'));
xmr.setNativeCnSlowHash(() => hexBytes(oracle.chachaKey));

const oracleFile = hexBytes(oracle.file);
const openedContainer = xmr.readContainer(oracleFile);
const opened = xmr.moneroFileToWire(
  openedContainer,
  xmr.readUnsignedTxSetFile(oracleFile, hexBytes(oracle.viewSecret)),
);

/* And the other shape the same screen has to render: a container this build
 * deliberately has no reader for. It decodes through the same type, with an
 * empty transaction list and a reason, which is the branch a `Decodable` that
 * had quietly made `problem` non-optional would fail on. */
const signedSet = new Uint8Array(24);
for (const [i, ch] of [...'Monero signed tx set'].entries()) signedSet[i] = ch.charCodeAt(0);
const closedContainer = xmr.readContainer(signedSet);
const closed = xmr.moneroFileToWire(closedContainer, {
  ok: false,
  problem: closedContainer.refusal,
});

if (opened.transactions.length !== 1 || opened.transactions[0].payingFormatted !== '2.4') {
  throw new Error('the monero file fixture does not describe the set the oracle produced');
}
if (closed.readable || closed.transactions.length !== 0) {
  throw new Error('the unreadable fixture is not unreadable');
}

writeFileSync(
  `${OUT_DIR}/monero-file.json`,
  JSON.stringify(
    {
      note:
        'Generated by scripts/emit-swift-fixtures.mjs from test/fixtures/monero-unsigned-tx-set.json, ' +
        "which came out of Monero's own binary_archive by way of oracle/. Through the real reader " +
        'and the real moneroFileToWire. Not written by hand and not to be edited by hand.',
      opened,
      closed,
    },
    null,
    1,
  ) + '\n',
);

/* The cross-language vectors, copied rather than symlinked: SwiftPM's resource
 * copying does not follow a symlink, and a resource that silently fails to
 * arrive turns a contract test into a test that passes by not running.
 * `test/bundle.test.ts` compares the two files byte for byte. */
writeFileSync(`${OUT_DIR}/primitives.json`, readFileSync('test/fixtures/primitives.json'));

console.log(`${OUT_DIR}/summary.json  ${summaries.ok.outputs.length} + ${summaries.refused.outputs.length} outputs`);
console.log(`${OUT_DIR}/monero-file.json  ${opened.transactions.length} transaction, plus one unreadable container`);
console.log(`${OUT_DIR}/primitives.json  copied from test/fixtures`);
