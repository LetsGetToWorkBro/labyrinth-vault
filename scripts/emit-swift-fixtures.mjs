/**
 * Give the Swift side something real to decode.
 *
 * `test/app-wiring.test.ts` checks that `TxSummary` in Swift and `WireSummary`
 * in TypeScript have the same field names and the same mapped types. It does
 * that by parsing both with regular expressions, which is crude, and it is
 * crude because until now nothing in this repository could compile Swift.
 *
 * Now something can. So instead of comparing two *descriptions* of a shape,
 * the Swift test decodes JSON that the TypeScript actually produced — from a
 * real PSBT, through the real reader, through the real `toWire`. A renamed
 * field, a nullable that stopped being nullable, a number that became a
 * string: `Decodable` fails on all of them, in the same way the app would fail
 * on a phone, without anybody having to describe the shape twice.
 *
 * Two summaries are emitted, and the second one matters more than the first:
 *
 *   - `ok`: an ordinary payment with change. Proves the happy path decodes.
 *   - `refused`: a transaction whose change output pays somebody else. Proves
 *     the refusal path decodes *and* that the fatal code carried in `refusal`
 *     is one the Swift `Refusal` enum has a case for — which is the thing
 *     that, if it broke, would put an unrecognised refusal in front of a
 *     person instead of the words for what actually happened.
 *
 * Regenerated by `npm run build:bundle`, committed, and checked for staleness
 * by `test/bundle.test.ts`. A fixture nobody regenerates is a fixture that
 * describes last month's shape.
 */

import { build } from 'esbuild';
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';

const OUT_DIR = 'ios/LabyrinthVaultTests/Fixtures';

/** Load TypeScript modules through the bundler that is already a dependency. */
async function load(entry) {
  return evaluate({ entryPoints: [entry] });
}

/**
 * The same, from source written here rather than from a file on disk.
 *
 * Needed because each `load` produces an independent bundle with an
 * independent copy of every module's state. Installing a host function into
 * one copy of `moneroexport.ts` and then calling a converter that closed over
 * a *different* copy would install nothing, silently — the derivation would
 * refuse, the file would not open, and the fixture would record a refusal as
 * though it were the shape. One entry point means one copy of everything.
 */
async function loadSource(contents) {
  return evaluate({ stdin: { contents, resolveDir: process.cwd(), loader: 'ts' } });
}

async function evaluate(input) {
  const compiled = await build({
    ...input,
    bundle: true,
    format: 'esm',
    write: false,
    platform: 'neutral',
  });
  return import(
    'data:text/javascript;base64,' +
      Buffer.from(compiled.outputFiles[0].text).toString('base64')
  );
}

const { addressAt, openFromMnemonic } = await load('src/keys/bitcoin.ts');
const { describePsbt } = await load('src/keys/psbt.ts');
const { toWire } = await load('src/bridge/summary.ts');
const btc = await load('node_modules/@scure/btc-signer/index.js');

/* The same two wallets test/psbt.test.ts uses: the BIP39 test vector, and a
 * second one standing in for everybody who is not us. Fixed words so the
 * fixture is byte-identical on every machine — a fixture that changes when
 * nothing changed is a fixture people stop regenerating. */
const WORDS =
  'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';
const STRANGER_WORDS =
  'legal winner thank year wave sausage worth useful legal winner thank yellow';

const wallet = openFromMnemonic(WORDS);
const stranger = openFromMnemonic(STRANGER_WORDS);
const STRANGER_ADDRESS = addressAt(stranger, 0, 0).address;

/** An output that claims one of our change paths, whoever it actually pays. */
function claiming(script, amount, change, index) {
  const node = wallet.account.deriveChild(change).deriveChild(index);
  return {
    script,
    amount,
    bip32Derivation: [
      [node.publicKey, { fingerprint: 0x12345678, path: [2147483732, 2147483648, 2147483648, change, index] }],
    ],
  };
}

const scriptFor = (address) => btc.OutScript.encode(btc.Address().decode(address));

/** An ordinary payment: one coin in, a stranger paid, change back to us. */
function payment() {
  const tx = new btc.Transaction({ allowUnknownOutputs: true });
  tx.addInput({
    txid: new Uint8Array(32).fill(3),
    index: 0,
    witnessUtxo: { script: addressAt(wallet, 0, 0).script, amount: 800_764n },
  });
  tx.addOutput({ script: scriptFor(STRANGER_ADDRESS), amount: 482_731n });
  tx.addOutput(claiming(addressAt(wallet, 1, 0).script, 317_891n, 1, 0));
  return tx.toPSBT();
}

/**
 * The change-swap attack, which is the one this whole screen exists to catch:
 * an output carrying a derivation path that really is ours, over a script that
 * pays somebody else. The reader re-derives from its own key, gets a different
 * script, and refuses.
 *
 * It is the second fixture because the refusal path has to decode too. A
 * `TxSummary` that parses the happy case and falls over on a refusal would put
 * an error screen in front of somebody at the exact moment the app has
 * something important to tell them.
 */
function changeSwap() {
  const tx = new btc.Transaction({ allowUnknownOutputs: true });
  tx.addInput({
    txid: new Uint8Array(32).fill(4),
    index: 0,
    witnessUtxo: { script: addressAt(wallet, 0, 0).script, amount: 200_000n },
  });
  tx.addOutput({ script: scriptFor(STRANGER_ADDRESS), amount: 150_000n });
  tx.addOutput(claiming(scriptFor(STRANGER_ADDRESS), 45_000n, 1, 0));
  return tx.toPSBT();
}

const summaries = {
  note:
    'Generated by scripts/emit-swift-fixtures.mjs from real PSBTs through the real reader. ' +
    'Not written by hand and not to be edited by hand: the point is that Swift decodes what ' +
    'TypeScript actually produces.',
  ok: toWire(describePsbt(payment(), wallet)),
  refused: toWire(describePsbt(changeSwap(), wallet)),
};

if (summaries.ok.refusal !== null) {
  throw new Error(`the "ok" fixture is refusing: ${summaries.ok.refusal}`);
}
if (summaries.refused.refusal !== 'output-path-mismatch') {
  throw new Error(`the "refused" fixture refused for the wrong reason: ${summaries.refused.refusal}`);
}

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(`${OUT_DIR}/summary.json`, JSON.stringify(summaries, null, 1) + '\n');

