/**
 * Generate the fastlane metadata tree from `store/`.
 *
 * ## Why generated rather than written
 *
 * `deliver` reads a directory of text files whose names it fixes:
 * `metadata/en-US/name.txt`, `subtitle.txt`, `description.txt` and so on. That
 * is a second copy of every string in `store/`, and `test/store.test.ts`
 * checks the copy in `store/` against Apple's length limits *and* against the
 * code, so a second hand-maintained copy is a second set of claims with none
 * of the checking.
 *
 * So the tree is generated and gitignored, `store/` stays the source, and the
 * upload carries exactly what the tests passed.
 *
 *   node scripts/make-fastlane.mjs
 *   fastlane deliver --app_identifier vision.labyrinth.vault
 *
 * ## What deliver will still ask for
 *
 * Everything that is a form toggle rather than a string: category, age rating,
 * the App Privacy questionnaire, pricing. Those live in App Store Connect and
 * `docs/shipping.md` § 6 has the answer written next to each one. This script
 * covers the text and the screenshots, which are the parts that are worth
 * automating because they are the parts that get retyped.
 */

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';

/** `store/` file to the name deliver insists on. */
const MAPPING = [
  ['name.txt', 'name.txt'],
  ['subtitle.txt', 'subtitle.txt'],
  ['description.txt', 'description.txt'],
  ['keywords.txt', 'keywords.txt'],
  ['promotional-text.txt', 'promotional_text.txt'],
  ['whats-new.txt', 'release_notes.txt'],
];

const APPS = [
  {
    slug: 'vault',
    bundleId: 'vision.labyrinth.vault',
    privacy: 'https://labyrinthwallet.com/vault/privacy',
  },
  {
    slug: 'wallet',
    bundleId: 'vision.labyrinth.wallet',
    privacy: 'https://labyrinthwallet.com/privacy',
  },
];

const SUPPORT_URL = 'https://labyrinthwallet.com';

function write(path, body) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body.endsWith('\n') ? body : `${body}\n`);
  return path;
}

const written = [];

for (const app of APPS) {
  const from = `store/${app.slug}`;
  const to = `fastlane/${app.slug}/metadata/en-US`;

  for (const [source, target] of MAPPING) {
    const path = `${from}/${source}`;
    if (!existsSync(path)) {
      throw new Error(`${path} is missing; the listing is incomplete`);
    }
    written.push(write(`${to}/${target}`, readFileSync(path, 'utf8').trim()));
  }

  written.push(write(`${to}/privacy_url.txt`, app.privacy));
  written.push(write(`${to}/support_url.txt`, SUPPORT_URL));
  written.push(write(`${to}/marketing_url.txt`, SUPPORT_URL));

  /* The review notes are markdown in `store/` because they are meant to be
   * read by us too. App Store Connect's field is plain text and renders none
   * of it, so the markers come out. Nothing is reworded: a reviewer should
   * get the same document, minus the syntax that would show up as literal
   * asterisks in a form field. */
  const notes = readFileSync(`${from}/review-notes.md`, 'utf8')
    .replace(/^#+\s*/gm, '')
    .replace(/\*\*(.+?)\*\*/gs, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  written.push(write(`fastlane/${app.slug}/metadata/review_information/notes.txt`, notes));

  /* There are no accounts in either app, so there is no demo account, and
   * saying so explicitly is better than leaving the field blank for a
   * reviewer who is looking for credentials. */
  written.push(write(`fastlane/${app.slug}/metadata/review_information/demo_user.txt`, ''));
  written.push(write(`fastlane/${app.slug}/metadata/review_information/demo_password.txt`, ''));

  write(
    `fastlane/${app.slug}/Deliverfile`,
    [
      '# Generated by scripts/make-fastlane.mjs. Do not edit.',
      '# The strings come from store/, which is what test/store.test.ts checks.',
      `app_identifier "${app.bundleId}"`,
      'submit_for_review false',
      '# Screenshots are taken by scripts/screenshots.sh, which checks each one',
      '# against the pixel sizes App Store Connect accepts before you get here.',
      `screenshots_path "./fastlane/${app.slug}/screenshots"`,
      `metadata_path "./fastlane/${app.slug}/metadata"`,
      '# Nothing is overwritten in App Store Connect that this repository does',
      '# not have a tested source for. Category, age rating and the privacy',
      '# questionnaire are set in the web UI; docs/shipping.md has the answers.',
      'overwrite_screenshots true',
      'force false',
      '',
    ].join('\n'),
  );
  written.push(`fastlane/${app.slug}/Deliverfile`);
}

for (const path of written) console.log(path);
console.log(`\n${written.length} files. Next: fastlane deliver --app_identifier ${APPS[0].bundleId}`);
